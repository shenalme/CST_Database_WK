// npm run bundle — packs docs/twin3d.js and the three.js libraries in docs/vendor into ONE ordinary script
// (docs/twin3d.bundle.js). Browsers refuse ES modules on pages opened by double-clicking a file (file://),
// so the twin page loads this bundle instead; it works from file://, a local server and GitHub Pages.
import { build } from 'esbuild';
import { join } from 'node:path';
import { ROOT } from './lib.mjs';

const docs = join(ROOT, 'docs');
const r = await build({
  entryPoints: [join(docs, 'twin3d.js')], bundle: true, format: 'iife', minify: true, target: 'es2019',
  alias: { three: join(docs, 'vendor', 'three.module.min.js') }, outfile: join(docs, 'twin3d.bundle.js'), legalComments: 'none',
  banner: { js: '/* AUTO-GENERATED by tools/bundle.mjs from twin3d.js + three.js (MIT, see vendor/three-LICENSE.txt). Do not edit. */' },
  logLevel: 'warning',
});
console.log('bundled docs/twin3d.bundle.js', r.errors.length ? r.errors : 'ok');
