// npm run models — embeds the models listed in docs/models/models.json into docs/models/models-embedded.js
// so they also load when twin.html is opened by double-click (browsers only allow fetching files from a web server).
// GitHub Pages and local servers work either way; the embedded copy is used when present.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib.mjs';

const dir = join(ROOT, 'docs', 'models'), manifest = JSON.parse(readFileSync(join(dir, 'models.json'), 'utf8')), out = {};
for (const [key, v] of Object.entries(manifest)) {
  if (key.startsWith('_') || !v || !v.file) continue;
  const p = join(dir, v.file);
  if (!existsSync(p)) { console.warn('missing model file', v.file); continue; }
  const { file, ...opts } = v;
  out[key] = { opts, data: readFileSync(p).toString('base64') };
}
writeFileSync(join(dir, 'models-embedded.js'), '// AUTO-GENERATED by tools/models.mjs from models.json. Do not edit.\nwindow.TWIN_MODELS = ' + JSON.stringify(out) + ';\n');
console.log('embedded models:', Object.keys(out).join(', ') || '(none)');
