-- =====================================================================
-- 1_schema.sql — tables, designed around the team's dashboard
-- (manufacturing_lca_comparison_html_example.html). Run once on an empty project.
-- Every table notes which part of the dashboard it serves.
-- =====================================================================

-- ---------- Section 2: project and part ----------
create table projects (
  project_id    bigint generated by default as identity primary key,
  project_code  varchar(50) unique,
  project_name  varchar(200) not null,          -- "Project"
  customer_name varchar(200),
  status        varchar(30) not null default 'active',
  created_at    timestamptz not null default now()
);

create table parts (
  part_id          bigint generated by default as identity primary key,
  project_id       bigint not null references projects (project_id),
  part_number      varchar(100) not null,       -- "Part number"
  part_description text,                        -- "Part description"
  functional_unit  varchar(200),                -- "Functional unit"
  length_mm        numeric check (length_mm >= 0),     -- plan area and volume are calculated from these
  width_mm         numeric check (width_mm >= 0),
  thickness_mm     numeric check (thickness_mm >= 0),
  notes            text,
  unique (project_id, part_number)
);

-- ---------- Section 3: materials list and BOM ----------
-- The material drop-down: carbon fibre, epoxy, peel ply ... with their factors.
create table materials (
  material_id          bigint generated by default as identity primary key,
  material_code        varchar(100) not null unique,
  material_name        varchar(200) not null,
  material_type        varchar(50)  not null
    check (material_type in ('Fibre', 'Resin', 'Adhesive', 'Consumable', 'Finishing', 'Packaging')),
  cf_kgco2e_per_kg     numeric not null,        -- carbon footprint, kg CO2e per kg
  ced_mj_per_kg        numeric not null,        -- cumulative energy demand, MJ per kg
  source_note          text,
  approved             boolean not null default false,   -- only approved factors enter calculations
  created_at           timestamptz not null default now()
);

-- Electricity factor, expected scrap, quantity and alert threshold are the inputs of sections 2 and 4.
-- A scenario = one part made by one route with one set of assumptions.
create table manufacturing_routes (          -- Section 4 route drop-down
  route_id    bigint generated by default as identity primary key,
  route_code  varchar(50)  not null unique,    -- vacuum_infusion, rtm, compression, prepreg_autoclave
  route_name  varchar(200) not null,
  description text
);

create table lca_scenarios (
  scenario_id             bigint generated by default as identity primary key,
  part_id                 bigint not null references parts (part_id),
  route_id                bigint not null references manufacturing_routes (route_id),
  scenario_name           varchar(200) not null,
  electricity_factor      numeric not null default 0.26155 check (electricity_factor >= 0),  -- kg CO2e per kWh
  expected_scrap_percent  numeric not null default 5  check (expected_scrap_percent >= 0),   -- "Expected scrap %"
  quantity                numeric not null default 1  check (quantity > 0),                  -- "Quantity"
  alert_threshold_percent numeric not null default 15 check (alert_threshold_percent >= 0),  -- "Live variance alert %"
  status                  varchar(30) not null default 'draft',
  created_at              timestamptz not null default now(),
  unique (part_id, scenario_name)
);

create table bom_items (                     -- the BOM table; "Add BOM item" inserts a row
  bom_item_id  bigint generated by default as identity primary key,
  scenario_id  bigint  not null references lca_scenarios (scenario_id) on delete cascade,
  material_id  bigint  not null references materials (material_id),
  stage        varchar(30) not null
    check (stage in ('Final laminate', 'Assembly', 'Consumable', 'Finishing', 'Packaging')),
  mass_kg      numeric not null check (mass_kg >= 0),            -- "Mass used (kg)"
  waste_percent numeric not null default 0 check (waste_percent >= 0),   -- "Waste %"
  consumed_kg  numeric generated always as (mass_kg * (1 + waste_percent / 100)) stored,  -- "Consumed kg"
  sequence_no  integer,
  notes        text
);
create index bom_items_scenario_idx on bom_items (scenario_id);

-- "Load example BOM" copies this template into a scenario.
create table bom_template_items (
  template_code varchar(50) not null,
  sort_order    integer not null,
  material_id   bigint not null references materials (material_id),
  stage         varchar(30) not null
    check (stage in ('Final laminate', 'Assembly', 'Consumable', 'Finishing', 'Packaging')),
  mass_kg       numeric not null,
  waste_percent numeric not null default 0,
  primary key (template_code, sort_order)
);

-- The layup definition mentioned under section 3 (ply count, fibre orientation,
-- fabric type, resin ratio, scrap). Not used in the totals, as in the mock-up.
create table layup_schedule (
  layup_id           bigint generated by default as identity primary key,
  scenario_id        bigint not null references lca_scenarios (scenario_id) on delete cascade,
  layer_no           integer not null,
  material_id        bigint references materials (material_id),
  fabric_type        varchar(200),
  ply_count          integer check (ply_count > 0),
  orientation_deg    numeric,
  resin_ratio_percent numeric check (resin_ratio_percent between 0 and 100),
  scrap_percent      numeric check (scrap_percent >= 0),
  notes              text,
  unique (scenario_id, layer_no)
);

-- ---------- Section 4: machines, routes and operations ----------
create table machines (
  machine_id     bigint generated by default as identity primary key,
  machine_name   varchar(200) not null unique,   -- "Machine" column
  machine_type   varchar(50),                     -- oven, autoclave, press, vacuum_pump, cnc ...
  rated_power_kw numeric check (rated_power_kw >= 0),
  notes          text
);

create table route_operations (                -- the route table: one row per process step
  route_operation_id bigint generated by default as identity primary key,
  route_id           bigint not null references manufacturing_routes (route_id) on delete cascade,
  op_no              integer not null check (op_no > 0),                   -- "ID"
  stage              varchar(30) not null check (stage in ('Manufacturing', 'Assembly', 'Finishing')),
  process_name       varchar(200) not null,                                -- "Process"
  machine_id         bigint references machines (machine_id),              -- "Machine"
  hours              numeric not null check (hours >= 0),                  -- "Hours"
  kw                 numeric not null check (kw >= 0),                     -- "kW"
  utilisation        numeric not null check (utilisation between 0 and 1), -- "Util."
  process_cf_per_kg  numeric not null default 0 check (process_cf_per_kg >= 0), -- "Process kg CO2e/kg"
  mass_basis_kg      numeric not null default 0 check (mass_basis_kg >= 0),     -- kg the process factor applies to
  expected_kwh       numeric generated always as (hours * kw * utilisation) stored,   -- "Expected kWh"
  notes              text,
  unique (route_id, op_no)
);

-- ---------- Section 6: live production energy data ----------
create table sensors (                         -- "Sensor / meter ID"
  sensor_code  varchar(100) primary key,
  machine_id   bigint references machines (machine_id),
  sensor_type  varchar(50) not null default 'energy meter',
  unit         varchar(20) not null default 'kWh',
  installed_at timestamptz
);

create table sensor_readings (                 -- "Add live reading" inserts a row
  reading_id         bigint generated by default as identity primary key,
  scenario_id        bigint not null references lca_scenarios (scenario_id) on delete cascade,
  route_operation_id bigint not null references route_operations (route_operation_id),   -- "Operation"
  sensor_code        varchar(100) not null references sensors (sensor_code),             -- "Sensor / meter ID"
  kwh                numeric not null check (kwh >= 0),                                  -- "Actual sensor kWh"
  machine_state      varchar(20) not null default 'running'
    check (machine_state in ('running', 'idle', 'standby', 'fault')),                    -- "Machine state"
  recorded_at        timestamptz not null default now(),
  run_label          varchar(100)                                                         -- optional batch / run reference
);
create index sensor_readings_scenario_op_idx on sensor_readings (scenario_id, route_operation_id);

-- A reading must belong to an operation of the scenario's own route.
create function check_reading_operation() returns trigger
language plpgsql set search_path = public
as $$
begin
  if not exists (select 1 from lca_scenarios s join route_operations ro on ro.route_id = s.route_id
                 where s.scenario_id = new.scenario_id and ro.route_operation_id = new.route_operation_id) then
    raise exception 'operation % is not part of the route of scenario %', new.route_operation_id, new.scenario_id;
  end if;
  return new;
end $$;
create trigger sensor_readings_operation_check before insert or update on sensor_readings
  for each row execute function check_reading_operation();

-- ---------- Sections 5 and 7: saved design vs live comparison ----------
-- The dashboard recalculates on screen; these tables store a saved copy so that the
-- AI prompt and recommendations refer to numbers that cannot change afterwards.
create table lca_snapshots (                   -- the KPI boxes of sections 5 and 7
  snapshot_id             bigint generated by default as identity primary key,
  scenario_id             bigint not null references lca_scenarios (scenario_id),
  calculation_version     varchar(50) not null,
  calculated_at           timestamptz not null default now(),
  electricity_factor      numeric not null,
  alert_threshold_percent numeric not null,
  bom_mass_kg             numeric,
  bom_kgco2e              numeric,          -- "BOM / materials"
  bom_ced_mj              numeric,
  manufacturing_kgco2e    numeric,          -- "Manufacturing"
  assembly_finishing_kgco2e numeric,        -- "Assembly + finishing"
  design_total_kgco2e     numeric,          -- "Total design LCA"
  design_ced_mj           numeric,
  design_kwh              numeric,
  live_kwh                numeric,
  live_total_kgco2e       numeric,          -- "Live total"
  variance_kgco2e         numeric,          -- "Variance"
  extra_kwh               numeric           -- "Extra kWh"
);

create table lca_comparison (                  -- the design vs live table, one row per operation
  comparison_id    bigint generated by default as identity primary key,
  snapshot_id      bigint not null references lca_snapshots (snapshot_id) on delete cascade,
  route_operation_id bigint not null references route_operations (route_operation_id),
  op_no            integer not null,
  stage            varchar(30),
  process_name     varchar(200),
  machine_name     varchar(200),
  design_kwh       numeric,
  live_kwh         numeric,
  variance_kwh     numeric,
  variance_percent numeric,
  status           varchar(20) not null check (status in ('ok', 'watch', 'high', 'no_live')),
  has_live_data    boolean not null,
  design_kgco2e    numeric,
  live_kgco2e      numeric,
  unique (snapshot_id, route_operation_id)
);

-- ---------- Section 8: AI improvement prompt ----------
-- The wording of the prompt is data, so the team can edit it without touching code.
create table ai_prompt_templates (
  template_id      bigint generated by default as identity primary key,
  template_code    varchar(50) not null unique,
  template_name    varchar(200) not null,
  role_text        text not null,     -- "You are an energy optimisation ... assistant."
  task_text        text not null,     -- "Analyse this composite product LCA comparison."
  questions_text   text not null,     -- the numbered "Please provide:" list
  constraints_text text not null,     -- "Do not recommend changing cure time ..."
  active           boolean not null default true
);

create table ai_prompts (                      -- every prompt that "Generate prompt" produced
  prompt_id   bigint generated by default as identity primary key,
  snapshot_id bigint not null references lca_snapshots (snapshot_id) on delete cascade,
  template_id bigint not null references ai_prompt_templates (template_id),
  context     jsonb not null,                -- the JSON data block inside the prompt
  prompt_text text  not null,                -- the complete text to paste into an AI tool
  created_at  timestamptz not null default now()
);

-- ---------- Section 9: recommendations ----------
create table recommendation_actions (          -- the standard "Suggested actions" list
  action_id   bigint generated by default as identity primary key,
  sort_order  integer not null,
  applies_to  varchar(50) not null default 'general',   -- general, oven_autoclave, vacuum_infusion, cnc_trimming
  action_text text not null,
  requires_engineering_validation boolean not null default false,
  active      boolean not null default true
);

create table ai_recommendations (              -- "AI output, action owner, saving estimate and validation status"
  recommendation_id  bigint generated by default as identity primary key,
  snapshot_id        bigint not null references lca_snapshots (snapshot_id) on delete cascade,
  scenario_id        bigint not null references lca_scenarios (scenario_id),
  route_operation_id bigint references route_operations (route_operation_id),
  source             varchar(20) not null default 'rule' check (source in ('rule', 'library', 'ai')),
  finding_type       varchar(30) not null check (finding_type in ('high_variance', 'suggested_action', 'note')),
  severity           varchar(20) not null default 'info' check (severity in ('info', 'watch', 'high')),
  recommendation_text text not null,
  estimated_kwh_saving  numeric,             -- for high variance: the excess over the design baseline
  estimated_co2e_saving numeric,
  action_owner       varchar(200),
  due_date           date,
  requires_engineering_validation boolean not null default true,
  validation_status  varchar(30) not null default 'proposed'
    check (validation_status in ('proposed', 'under_review', 'approved', 'rejected', 'implemented')),
  created_at         timestamptz not null default now()
);

-- After loading rows with explicit ids (CSV import) call:  select reset_identity_sequences();
create function reset_identity_sequences() returns void
language plpgsql set search_path = public
as $$
declare r record;
begin
  for r in select table_name, column_name from information_schema.columns
           where table_schema = 'public' and is_identity = 'YES'
  loop
    execute format('select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(%I) from public.%I), 0) + 1, false)',
                   'public.' || r.table_name, r.column_name, r.column_name, r.table_name);
  end loop;
end $$;
