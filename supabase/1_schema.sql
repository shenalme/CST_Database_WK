-- ---------- A. Project and scenario tables ----------
create table organisations (
  organisation_id   bigint generated by default as identity primary key,
  organisation_name varchar(200) not null,
  organisation_code varchar(50)  not null unique,
  created_at        timestamptz  not null default now()
);

create table projects (
  project_id      bigint generated by default as identity primary key,
  organisation_id bigint       not null references organisations (organisation_id),
  project_code    varchar(50)  not null,
  project_name    varchar(200) not null,
  customer_name   varchar(200),
  start_date      date,
  end_date        date,
  status          varchar(30),
  created_at      timestamptz  not null default now(),
  unique (organisation_id, project_code)
);

create table parts (
  part_id          bigint generated by default as identity primary key,
  project_id       bigint       not null references projects (project_id),
  part_number      varchar(100) not null,
  part_description text,
  functional_unit  varchar(200),
  quantity         numeric,
  length_mm        numeric,
  width_mm         numeric,
  thickness_mm     numeric,
  notes            text,
  unique (project_id, part_number)               -- "part number should be unique within a project"
);

create table lca_scenarios (
  scenario_id         bigint generated by default as identity primary key,
  part_id             bigint       not null references parts (part_id),
  scenario_name       varchar(200) not null,
  goal                text,
  system_boundary     varchar(100),
  quantity            numeric,
  electricity_factor  numeric,                   -- kg CO2e per kWh of grid electricity for this scenario
  data_quality_target varchar(100),
  status              varchar(30),
  created_at          timestamptz not null default now(),
  approved_at         timestamptz,
  unique (part_id, scenario_name)
);

-- ---------- B. Reference and environmental data ----------
create table lifecycle_stages (
  stage_id    bigint generated by default as identity primary key,
  stage_code  varchar(20)  not null unique,
  stage_name  varchar(100) not null,
  sequence_no integer      not null
);

create table lca_items (
  item_id                  bigint generated by default as identity primary key,
  item_code                varchar(100) not null unique,
  item_name                varchar(200) not null,
  item_type                varchar(50)  not null
    check (item_type in ('material', 'process', 'use_phase', 'end_of_life')),
  default_unit             varchar(50),
  assumptions              text,
  impact_assessment_method varchar(200),
  iso_compliant            boolean,
  notes                    text,
  active                   boolean not null default true
);

create table impact_categories (
  impact_category_id bigint generated by default as identity primary key,
  impact_code        varchar(30)  not null unique,
  impact_name        varchar(200) not null,
  unit               varchar(50)  not null,
  description        text
);

create table lca_factors (
  factor_id          bigint generated by default as identity primary key,
  item_id            bigint  not null references lca_items (item_id),
  impact_category_id bigint  not null references impact_categories (impact_category_id),
  factor_value       numeric not null,
  factor_unit        varchar(50),
  basis_unit         varchar(50),
  valid_from         date,
  valid_to           date,
  data_quality       varchar(50),
  source_method      varchar(200),
  approved           boolean not null default false,
  created_at         timestamptz not null default now()
);

create table sources (
  source_id        bigint generated by default as identity primary key,
  source_name      varchar(250) not null,
  source_type      varchar(50),
  citation         text,
  url              text,
  publication_year integer,
  database_name    varchar(200),
  version          varchar(50),
  notes            text
);

create table item_sources (
  item_source_id  bigint generated by default as identity primary key,
  item_id         bigint not null references lca_items (item_id),
  source_id       bigint not null references sources (source_id),
  reference_order integer,
  notes           text,
  unique (item_id, source_id)
);

create table material_properties (
  material_property_id bigint generated by default as identity primary key,
  item_id              bigint       not null references lca_items (item_id),
  property_name        varchar(100) not null,
  property_value       numeric,
  unit                 varchar(50),
  source_id            bigint references sources (source_id),
  notes                text
);

-- ---------- C. Equipment and manufacturing tables ----------
create table equipment (
  equipment_id    bigint generated by default as identity primary key,
  organisation_id bigint       not null references organisations (organisation_id),
  equipment_code  varchar(100) not null,
  equipment_name  varchar(200) not null,
  equipment_type  varchar(100),
  manufacturer    varchar(200),
  model           varchar(200),
  location        varchar(200),
  rated_power_kw  numeric,
  used_for        text,
  assumptions     text,
  notes           text,
  active          boolean not null default true,
  unique (organisation_id, equipment_code)
);

create table equipment_factors (
  equipment_factor_id bigint generated by default as identity primary key,
  equipment_id        bigint  not null references equipment (equipment_id),
  impact_category_id  bigint  not null references impact_categories (impact_category_id),
  factor_value        numeric not null,
  factor_unit         varchar(50),
  basis_unit          varchar(50),
  source_id           bigint references sources (source_id),
  approved            boolean not null default false
);

create table bom_items (
  bom_item_id      bigint generated by default as identity primary key,
  scenario_id      bigint  not null references lca_scenarios (scenario_id),
  item_id          bigint  not null references lca_items (item_id),
  stage_id         bigint  not null references lifecycle_stages (stage_id),
  net_quantity     numeric not null check (net_quantity >= 0),
  unit             varchar(50) not null,
  waste_percentage numeric not null default 0 check (waste_percentage >= 0 and waste_percentage < 100),
  sequence_no      integer,
  notes            text
);

create table scenario_operations (
  operation_id              bigint generated by default as identity primary key,
  scenario_id               bigint  not null references lca_scenarios (scenario_id),
  operation_sequence        integer not null,
  lifecycle_stage_id        bigint  not null references lifecycle_stages (stage_id),
  process_item_id           bigint  references lca_items (item_id),
  equipment_id              bigint  references equipment (equipment_id),
  operation_name            varchar(200) not null,
  expected_duration_minutes numeric check (expected_duration_minutes >= 0),
  expected_power_kw         numeric check (expected_power_kw >= 0),
  utilisation_factor        numeric check (utilisation_factor between 0 and 1),
  expected_energy_kwh       numeric,             -- per cycle (= minutes/60 x kW x utilisation)
  batch_size                integer check (batch_size > 0),   -- parts per cycle
  process_mass_basis        numeric,
  notes                     text,
  unique (scenario_id, operation_sequence)
);

-- ---------- D. Production and live-data tables (empty until Stage 2) ----------
create table production_batches (
  batch_id         bigint generated by default as identity primary key,
  scenario_id      bigint       not null references lca_scenarios (scenario_id),
  batch_code       varchar(100) not null unique,
  part_id          bigint       references parts (part_id),
  planned_quantity integer,
  actual_quantity  integer,
  scrap_quantity   integer,
  rework_quantity  integer,
  start_time       timestamptz,
  end_time         timestamptz,
  status           varchar(30)
);

create table sensor_devices (
  sensor_id                 bigint generated by default as identity primary key,
  equipment_id              bigint       not null references equipment (equipment_id),
  sensor_code               varchar(100) not null unique,
  sensor_name               varchar(200),
  sensor_type               varchar(100),
  measurement_type          varchar(100),
  unit                      varchar(50),
  sampling_interval_seconds integer,
  protocol                  varchar(50),
  active                    boolean not null default true,
  installed_at              timestamptz
);

-- Plain PostgreSQL is enough for now (no TimescaleDB). Primary key (sensor, time) keeps
-- the table ready to become a hypertable later. 'energy' readings = kWh in the interval.
create table sensor_readings (
  sensor_id        bigint      not null references sensor_devices (sensor_id),
  recorded_at      timestamptz not null,
  batch_id         bigint references production_batches (batch_id),
  operation_id     bigint references scenario_operations (operation_id),
  value            numeric     not null,
  unit             varchar(50),
  machine_state    varchar(50),
  quality_flag     varchar(50),
  ingestion_source varchar(100),
  received_at      timestamptz not null default now(),
  primary key (sensor_id, recorded_at)
);
create index sensor_readings_batch_op_idx on sensor_readings (batch_id, operation_id);

create table lca_results (
  result_id           bigint generated by default as identity primary key,
  scenario_id         bigint      not null references lca_scenarios (scenario_id),
  batch_id            bigint      references production_batches (batch_id),
  result_type         varchar(30) not null,        -- 'design' or 'measured'
  impact_category_id  bigint      not null references impact_categories (impact_category_id),
  lifecycle_stage_id  bigint      not null references lifecycle_stages (stage_id),
  result_value        numeric     not null,
  unit                varchar(50),
  calculation_version varchar(50),
  calculated_at       timestamptz not null default now()
);

-- The note names this table but lists no fields; these are the minimum needed.
create table operation_energy_comparison (
  comparison_id    bigint generated by default as identity primary key,
  batch_id         bigint  not null references production_batches (batch_id),
  operation_id     bigint  not null references scenario_operations (operation_id),
  expected_kwh     numeric,
  measured_kwh     numeric,
  expected_co2e_kg numeric,
  measured_co2e_kg numeric,
  calculated_at    timestamptz not null default now(),
  unique (batch_id, operation_id)
);

create table ai_recommendations (
  recommendation_id               bigint generated by default as identity primary key,
  scenario_id                     bigint not null references lca_scenarios (scenario_id),
  batch_id                        bigint references production_batches (batch_id),
  operation_id                    bigint references scenario_operations (operation_id),
  recommendation_text             text   not null,
  estimated_kwh_saving            numeric,
  estimated_co2e_saving           numeric,
  risk_level                      varchar(30),
  requires_engineering_validation boolean not null default true,
  validation_status               varchar(30),
  created_at                      timestamptz not null default now()
);

-- The note names this table but lists no fields; owner, due date, status, outcome as described.
create table energy_actions (
  action_id          bigint generated by default as identity primary key,
  recommendation_id  bigint references ai_recommendations (recommendation_id),
  action_description text not null,
  owner_name         varchar(200),
  due_date           date,
  status             varchar(30),
  validation_outcome text
);

-- After loading rows with explicit ids (CSV import) call:  select reset_identity_sequences();
create function reset_identity_sequences() returns void
language plpgsql set search_path = public
as $$
declare r record;
begin
  for r in select table_name, column_name from information_schema.columns
           where table_schema = 'public' and is_identity = 'YES'
  loop
    execute format('select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(%I) from public.%I), 0) + 1, false)',
                   'public.' || r.table_name, r.column_name, r.column_name, r.table_name);
  end loop;
end $$;
