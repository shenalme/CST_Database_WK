-- =====================================================================
-- 4_digital_twin.sql — floor layout for the digital twin (additive: run after 1, 2 and 3;
-- nothing already installed changes). Positions are in METRES on a floor plan.
-- The twin page (twin.html) draws these and simulates parts flowing through the
-- machines using the route operations, energy and live readings already in the database.
-- =====================================================================
create table factory_floors (
  floor_id   bigint generated by default as identity primary key,
  floor_name varchar(100) not null unique,
  width_m    numeric not null check (width_m > 0),
  height_m   numeric not null check (height_m > 0),
  notes      text
);

create table factory_zones (
  zone_id   bigint generated by default as identity primary key,
  floor_id  bigint not null references factory_floors (floor_id) on delete cascade,
  zone_name varchar(100) not null,
  x_m       numeric not null,
  y_m       numeric not null,
  width_m   numeric not null check (width_m > 0),
  height_m  numeric not null check (height_m > 0),
  colour    varchar(20),
  notes     text,
  unique (floor_id, zone_name)
);

-- One footprint per machine: top-left corner and size in metres.
create table machine_locations (
  machine_id bigint primary key references machines (machine_id) on delete cascade,
  floor_id   bigint not null references factory_floors (floor_id),
  zone_id    bigint references factory_zones (zone_id),
  x_m        numeric not null,
  y_m        numeric not null,
  width_m    numeric not null default 3 check (width_m > 0),
  height_m   numeric not null default 2 check (height_m > 0),
  notes      text
);

-- ---------- read-only feeds for the twin page ----------
create view v_dash_floor as
select floor_id, floor_name, width_m, height_m from factory_floors;

create view v_dash_floor_zones as
select zone_id, floor_id, zone_name, x_m, y_m, width_m, height_m, colour from factory_zones;

-- Machine footprint + rated power + the machine's most recent live reading
create view v_dash_floor_machines as
select m.machine_id, m.machine_name, m.machine_type, m.rated_power_kw,
       l.floor_id, l.zone_id, l.x_m, l.y_m, l.width_m, l.height_m,
       lv.machine_state as latest_state, lv.kwh as latest_kwh, lv.sensor_code as latest_sensor, lv.recorded_at as latest_recorded_at
from machines m
join machine_locations l on l.machine_id = m.machine_id
left join lateral (
  select sr.machine_state, sr.kwh, sr.sensor_code, sr.recorded_at
  from sensor_readings sr join route_operations ro on ro.route_operation_id = sr.route_operation_id
  where ro.machine_id = m.machine_id order by sr.recorded_at desc limit 1) lv on true;

-- ---------- security (same rules as the other tables) ----------
do $$
declare t text;
begin
  foreach t in array array['factory_floors', 'factory_zones', 'machine_locations'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy team_access on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;
revoke all on factory_floors, factory_zones, machine_locations from anon;
revoke all on v_dash_floor, v_dash_floor_zones, v_dash_floor_machines from anon;
grant select, insert, update, delete on factory_floors, factory_zones, machine_locations to authenticated;
grant select on v_dash_floor, v_dash_floor_zones, v_dash_floor_machines to authenticated;
grant usage, select on all sequences in schema public to authenticated;

comment on table factory_floors is 'Digital twin: a floor plan (size in metres).';
comment on table factory_zones is 'Digital twin: named areas of the floor (halls, cells).';
comment on table machine_locations is 'Digital twin: where each machine stands (top-left corner and footprint, metres). Drag machines on twin.html and copy the generated SQL to change them.';
